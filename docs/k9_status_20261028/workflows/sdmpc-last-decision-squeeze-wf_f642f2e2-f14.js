const HUNT_SCHEMA = {
  type: 'object',
  properties: {
    angle: { type: 'string' },
    prior_rejection: { type: 'string', description: 'Any existing record that this was already tried, quoted with its file. "none found, and here is where I looked" if so.' },
    finding: { type: 'string', description: 'What you established, with file:line and exact numbers.' },
    proposals: {
      type: 'array',
      items: {
        type: 'object',
        properties: {
          change: { type: 'string' },
          saving_sec: { type: 'string', description: 'Per rollout AND per decision, with the arithmetic.' },
          basis: { type: 'string', enum: ['MEASURED', 'DERIVED', 'ESTIMATED'] },
          decision_effect: { type: 'string', enum: ['NEUTRAL', 'CHANGING'] },
          decision_cost: { type: 'string', description: 'For CHANGING: what the objective loses, numerically if known. For NEUTRAL: the argument it is neutral.' },
          risk: { type: 'string' },
          effort: { type: 'string' },
        },
        required: ['change', 'saving_sec', 'basis', 'decision_effect', 'decision_cost', 'risk', 'effort'],
      },
    },
    dead_ends: { type: 'string', description: 'What you ruled out and why, so nobody repeats it.' },
  },
  required: ['angle', 'prior_rejection', 'finding', 'proposals', 'dead_ends'],
}

