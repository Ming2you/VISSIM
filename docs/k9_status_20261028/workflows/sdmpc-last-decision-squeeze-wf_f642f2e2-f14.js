const results = await pipeline(
  ANGLES,
  a => agent(CONTEXT + '\n\n' + a.prompt, {
    label: 'hunt:' + a.key,
    phase: 'Hunt',
    schema: HUNT_SCHEMA,
  }),
  (hunted, angle) => {
    if (!hunted) return null
    return agent([
      CONTEXT,
      '',
      'You are ADVERSARIALLY VERIFYING another analyst on: ' + hunted.angle,
      '',
      'Three tests, in order of importance:',
      '  1. WAS IT ALREADY REJECTED? Search diagnostics/ and docs/ yourself for a prior',
      '     measurement of each proposal. The single most common failure in this project is',
      '     re-proposing something that was measured and found slower. If the analyst reported',
      '     "no prior rejection found", look again in the places they did not.',
      '  2. IS THE SAVING REAL? Re-derive every number. A saving inside the forward primal only',
      '     counts if it survives the 5 serial batches; a saving in a threaded region is bounded',
      '     by how small that region already is (reverse_sec is 2.65 s -- nothing there is worth',
      '     more than 2.65 s).',
      '  3. IS "DECISION-NEUTRAL" EARNED? Neutrality is a property of the recorded evidence, not',
      '     of an argument that the maths looks the same. Pruning an axis, coarsening a step or',
      '     skipping a batch changes what the optimiser sees. Demand the specific mechanism.',
      '',
      'Be willing to say the analyst found nothing. That is an acceptable and useful outcome',
      'here -- the cheap levers really are gone, and a false positive costs hours of wasted run.',
      '',
      'THEIR PRIOR-REJECTION SEARCH: ' + hunted.prior_rejection,
      '',
      'THEIR FINDING:',
      hunted.finding,
      '',
      'THEIR PROPOSALS:',
      (hunted.proposals || []).map((p, i) =>
        [(i + 1) + '. ' + p.change,
         '   saving: ' + p.saving_sec + '  [' + p.basis + ', ' + p.decision_effect + ']',
         '   decision cost: ' + p.decision_cost,
         '   risk: ' + p.risk + '   effort: ' + p.effort].join('\n')).join('\n'),
      '',
      'THEIR DEAD ENDS: ' + hunted.dead_ends,
    ].join('\n'), {
      label: 'verify:' + angle.key,
      phase: 'Verify',
      schema: VERIFY_SCHEMA,
    }).then(v => ({ key: angle.key, hunted, verdict: v }))
  }
)

return {
  angles: results.filter(Boolean),
  note: 'Caller synthesises a single ranked list: decision-neutral savings first, then decision-changing ones with their objective cost.',
}
