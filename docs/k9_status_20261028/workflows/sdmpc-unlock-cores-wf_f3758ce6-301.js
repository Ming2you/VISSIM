const AUDIT_SCHEMA = {
  type: 'object',
  properties: {
    topic: { type: 'string' },
    verdict: {
      type: 'string',
      enum: ['ENABLE', 'ENABLE_WITH_CONDITIONS', 'NEEDS_WORK', 'DO_NOT_ENABLE', 'INCONCLUSIVE'],
    },
    why_off: { type: 'string', description: 'Rejected (with the rejection evidence) or never promoted (with what is missing).' },
    decision_neutral: { type: 'string', description: 'The recorded equivalence verdict, quoted, with its file. Or "no such record".' },
    saving: { type: 'string', description: 'Wall saved per taped rollout and per decision, with the basis (MEASURED where / DERIVED how / ESTIMATED from what).' },
    cores: { type: 'string', description: 'Does it use >1 core? Is anything capping it (OMP/MKL/NUMBA_NUM_THREADS, set_num_threads, GIL)?' },
    how_to_enable: { type: 'string', description: 'Exact config keys and values, plus any dependency flags.' },
    risk: { type: 'string' },
  },
  required: ['topic', 'verdict', 'why_off', 'decision_neutral', 'saving', 'cores', 'how_to_enable', 'risk'],
}

const VERIFY_SCHEMA = {
  type: 'object',
  properties: {
    refuted: { type: 'boolean' },
    confirmed: { type: 'string' },
    refutation: { type: 'string' },
    corrected_verdict: {
      type: 'string',
      enum: ['ENABLE', 'ENABLE_WITH_CONDITIONS', 'NEEDS_WORK', 'DO_NOT_ENABLE', 'INCONCLUSIVE'],
    },
    corrected_saving: { type: 'string' },
  },
  required: ['refuted', 'confirmed', 'refutation', 'corrected_verdict', 'corrected_saving'],
}

