phase('Audit')

const results = await pipeline(
  TOPICS,
  t => agent(CONTEXT + '\n\n' + t.prompt, {
    label: 'audit:' + t.key,
    phase: 'Audit',
    schema: AUDIT_SCHEMA,
  }),
  (audited, topic) => {
    if (!audited) return null
    return agent([
      CONTEXT,
      '',
      'You are ADVERSARIALLY VERIFYING another analyst on: ' + audited.topic,
      'Default to refuting. The cost of a wrong ENABLE here is a multi-hour run that silently',
      'computes a different answer, so weight false positives far more heavily than false negatives.',
      '',
      'Check specifically:',
      '  - Is the quoted decision-neutrality record REAL? Open the file and read the verdict',
      '    yourself. A code-reading argument is NOT an equivalence proof.',
      '  - Is a saving labelled MEASURED actually measured, and measured of the right thing?',
      '    A kernel that only speeds the untaped scalar rollout cannot claim taped-rollout savings.',
      '  - Does the flag have an unstated dependency, or does it interact with one of the ten flags',
      '    already on (especially sdmpc_fifo_batch, sdmpc_prediction_hotpath, sdmpc_compact_audit)?',
      '  - Is there a rejection record the analyst missed? Search for it before accepting',
      '    "never promoted".',
      '',
      'THEIR VERDICT: ' + audited.verdict,
      'WHY OFF: ' + audited.why_off,
      'DECISION NEUTRAL: ' + audited.decision_neutral,
      'SAVING: ' + audited.saving,
      'CORES: ' + audited.cores,
      'HOW TO ENABLE: ' + audited.how_to_enable,
      'RISK: ' + audited.risk,
    ].join('\n'), {
      label: 'verify:' + topic.key,
      phase: 'Verify',
      schema: VERIFY_SCHEMA,
    }).then(v => ({ key: topic.key, audited, verdict: v }))
  }
)

return {
  topics: results.filter(Boolean),
  note: 'Caller synthesises: which flags to turn on, the combined projected decision wall, and the full-run hours.',
}
