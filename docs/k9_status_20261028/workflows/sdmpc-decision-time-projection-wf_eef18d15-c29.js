phase('Measure')

const results = await pipeline(
  TOPICS,
  t => agent(CONTEXT + '\n\n' + t.prompt, {
    label: 'measure:' + t.key,
    phase: 'Measure',
    schema: MEASURE_SCHEMA,
  }),
  (measured, topic) => {
    if (!measured) return null
    return agent([
      CONTEXT,
      '',
      'You are ADVERSARIALLY VERIFYING another analyst\'s work on: ' + measured.topic,
      'Default to refuting. Reproduce every load-bearing number yourself from the archives and',
      'the source. Check arithmetic. Check that cited line numbers say what is claimed. Check that',
      'a number labelled MEASURED really was measured and not inferred.',
      '',
      'Pay special attention to:',
      '  - serial vs concurrent confusions (a batch wall is not the sum of its rollouts)',
      '  - fixed per-batch cost being double counted across batches',
      '  - any claim about what happens at 6 iterations that is extrapolated from 2',
      '  - whether an early-exit or convergence test makes 6 iterations unreachable',
      '',
      'THEIR FINDING:',
      measured.finding,
      '',
      'THEIR NUMBERS:',
      (measured.numbers || []).map(n => '  ' + n.label + ' = ' + n.value + '   [' + n.basis + ']').join('\n'),
      '',
      'THEIR STATED UNCERTAINTY:',
      measured.uncertainty,
    ].join('\n'), {
      label: 'verify:' + topic.key,
      phase: 'Verify',
      schema: VERIFY_SCHEMA,
    }).then(v => ({ key: topic.key, measured, verdict: v }))
  }
)

return {
  topics: results.filter(Boolean),
  note: 'Synthesis is done by the caller: derive one lower-level iteration cost, then project 3 budget candidates x 6 lower-level iterations on the current merged tree.',
}
