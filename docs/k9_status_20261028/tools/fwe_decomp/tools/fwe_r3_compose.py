"""fwe_r3_compose.py - R3_REPORT.md = narrative template (out/R3_REPORT.tmpl.md) with '@@표 X@@' lines replaced by the
matching '### 표 X.' block of out/R3_TABLES.md (generated by fwe_r3_md.py). No numbers are computed here.
python -B fwe_r3_compose.py . D-K9-106, 2026-10-27 KST."""
import re

FD = 'C:/Users/TRLAB/AppData/Local/Temp/claude/C--Users-TRLAB-Desktop----/491ef689-f002-4605-9dc5-e6d363495788/scratchpad/k8/fwe_decomp'


def main():
    tab = open(FD + '/out/R3_TABLES.md', encoding='utf-8').read().splitlines()
    blocks = {}
    cur = None
    for line in tab:
        m = re.match(r'^### 표 ([A-Z][0-9]+)\.', line)
        if m:
            cur = m.group(1)
            blocks[cur] = []
        if cur:
            blocks[cur].append(line)
    out = []
    used = set()
    for line in open(FD + '/out/R3_REPORT.tmpl.md', encoding='utf-8').read().splitlines():
        m = re.match(r'^@@표 ([A-Z][0-9]+)@@$', line.strip())
        if m:
            k = m.group(1)
            out.extend(blocks[k])
            used.add(k)
        else:
            out.append(line)
    missing = sorted(set(blocks) - used)
    if missing:
        raise SystemExit(f'tables not placed: {missing}')
    open(FD + '/R3_REPORT.md', 'w', encoding='utf-8').write('\n'.join(out).rstrip() + '\n')
    print('ok', len(out), 'tables', len(used))


if __name__ == '__main__':
    main()
