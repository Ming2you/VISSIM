def an(k):
    if '-s' in k:
        a, s = k.split('-s')
        return f'{ARM_NAME[a]} v3c3-s{s}'
    return ARM_NAME[k]


def f(x, n=1, sign=True):
    if x is None:
        return '—'
    if isinstance(x, str):
        return x
    v = round(x, n)
    if v == 0:
        v = 0.0
    s = f'{abs(v):,.{n}f}'
    if v < 0:
        return '−' + s
    return ('+' + s) if sign and v > 0 else s


def t(x):
    return '—' if x is None else f'{int(x):,}'


def blocks(v, nb, mode='sum'):
    out = []
    for b in range(nb):
        seg = v[3 * b:3 * b + 3]
        if any(x is None for x in seg):
            out.append(None)
        else:
            out.append(sum(seg) if mode == 'sum' else sum(seg) / 3.0)
    return out


