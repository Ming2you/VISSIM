# -*- coding: utf-8 -*-
"""Render FD/out/R1_nc.json into markdown tables FD/out/R1_tables.md (formatting only; no new numbers). 2026-10-27 KST.
python -B fwe_r1_md.py
900 s blocks are built from the 300 s arrays: veh-h and minutes add, speed = sum(V)/sum(N), rates = mean of 3 equal windows.
"""
import hashlib, json

FD = 'C:/Users/TRLAB/AppData/Local/Temp/claude/C--Users-TRLAB-Desktop----/491ef689-f002-4605-9dc5-e6d363495788/scratchpad/k8/fwe_decomp'
ARMS = ['v3c3-s31', 'v3c3-s41', 'v3c3-s43', '64cf-s29 LNC']
Z5 = ['U_0_4200', 'B1_4200_5300', 'M_5300_6800', 'B2_6800_7900', 'D_7900_10784']
Z5N = {'U_0_4200': 'U 0–4,200', 'B1_4200_5300': 'B1 4,200–5,300', 'M_5300_6800': 'M 5,300–6,800',
       'B2_6800_7900': 'B2 6,800–7,900', 'D_7900_10784': 'D 7,900–10,800'}
Z7 = ['U', 'B1', 'M1', 'Mu', 'VS0', 'B2', 'D']
BLK = [(j * 900, j * 900 + 900) for j in range(10)]
RAMPS = ['10639', '10681', '10490', '10484']
OFFS = ['10643', '10682', '10481', '10483']


def f(x, nd=1):
    if x is None:
        return '–'
    if isinstance(x, (int,)) and not isinstance(x, bool):
        return '{:,}'.format(x)
    return '{:,.{}f}'.format(x, nd)


def blk_sum(a):
    return [sum(a[3 * j:3 * j + 3]) for j in range(10)]


def blk_speed(vs, vf):
    return [(sum(vs[3 * j:3 * j + 3]) / sum(vf[3 * j:3 * j + 3])) if sum(vf[3 * j:3 * j + 3]) else None for j in range(10)]


def blk_rate(a):
    return [sum(a[3 * j:3 * j + 3]) / 3.0 for j in range(10)]


def rng(a, b):
    return '–' if a is None else '%s–%s' % (f(a), f(b))


def hdr_blocks():
    return '| ' + ' | '.join('%d–%d' % (a, b) for a, b in BLK)


def main():
    p = FD + '/out/R1_nc.json'
    raw = open(p, 'rb').read()
    R = json.loads(raw.decode('utf-8'))
    L = []
    L.append('<!-- generated by tools/fwe_r1_md.py from out/R1_nc.json sha256 %s -->' % hashlib.sha256(raw).hexdigest())
    A = {k: R['arms'][k]['R1'] for k in ARMS if 'R1' in R['arms'].get(k, {})}
    # T1
    L.append('\n### T1. R1-a ① FW_E 본선 7링크 수준 (veh·h)\n')
    L.append('| 런 | ① 우리 꼴 [0, 9000] | ① codex 꼴 [0, 8100] | fwe_scan 체인 bin 합 [0, 9000) − ① 우리 꼴 |')
    L.append('|---|---:|---:|---:|')
    for k in ARMS + ['64cf-s29 codex NC']:
        a = R['R1a'].get(k)
        if not a:
            continue
        ck = R['arms'][k].get('check_chain_bin_vs_fwe7_ours_9000')
        L.append('| %s | %s | %s | %s |' % (k, f(a['fwe7_ours_9000']), f(a['fwe7_codex_8100']), f(ck, 3) if ck is not None else '(스캔 없음)'))
    L.append('\n- LNC 와 codex NC 의 링크 적분 최대 차(두 꼴, 모든 링크): %s veh·h.' % f(R.get('R1a_check_lnc_vs_codex_nc_max_abs_link_diff'), 9))
    # T2 speed / veh-h by 900 s
    L.append('\n### T2. R1-b 다섯 구역 평균 속도 (km/h, ΣV/ΣN, 900 s 칸)\n')
    L.append('| 구역 | 런 ' + hdr_blocks() + ' | 0–9000 |')
    L.append('|---|---' + '|---:' * 11 + '|')
    for z in Z5:
        for k in ARMS:
            s = A[k]['R1b_R1c_zones5'][z]
            sp = blk_speed(s['speed_sum_300'], s['vehicle_frames_300'])
            L.append('| %s | %s | %s | %s |' % (Z5N[z], k, ' | '.join(f(x) for x in sp), f(s['mean_speed_kmh_0_9000'])))
    L.append('\n### T3. R1-b 다섯 구역 재고 (veh·h, 대수 × 5 s, 900 s 칸)\n')
    L.append('| 구역 | 런 ' + hdr_blocks() + ' | 0–9000 |')
    L.append('|---|---' + '|---:' * 11 + '|')
    for z in Z5:
        for k in ARMS:
            s = A[k]['R1b_R1c_zones5'][z]
            vh = blk_sum(s['veh_h_300'])
            L.append('| %s | %s | %s | %s |' % (Z5N[z], k, ' | '.join(f(x) for x in vh), f(s['veh_h_0_9000'])))
    # T4 congestion minutes and onset (5 zones)
    L.append('\n### T4. R1-c·d 다섯 구역 혼잡 분(혼잡 칸 ≥ 1 인 60 s 창 수)과 막힘 시작\n')
    L.append('| 구역 | 런 ' + hdr_blocks() + ' | 합 | 시작 (s) | 시작 창의 머리 (x m · 셀 · 링크, *=구역 안) |')
    L.append('|---|---' + '|---:' * 12 + '|---|')
    for z in Z5:
        for k in ARMS:
            s = A[k]['R1b_R1c_zones5'][z]
            o = A[k]['R1d_onset']['zones5'][z]
            hs = ', '.join('%s%d·c%s·%s' % ('*' if h['in_set'] else '', h['x_m'], h['cell'], h['link']) for h in o['heads_in_onset_window']) or '–'
            L.append('| %s | %s | %s | %d | %s | %s |' % (Z5N[z], k, ' | '.join(f(x) for x in blk_sum(s['cong_minutes_300'])),
                                                        s['cong_minutes_all_windows'], f(o['onset_s']), hs))
    # T5 seven zones (aux)
    L.append('\n### T5. R1-b·c·d 일곱 구역(보조, vsl_metrics.py:56) 0–9000 요약\n')
    L.append('| 구역 | ' + ' | '.join('%s veh·h / km/h / 혼잡 분 / 시작 s' % k for k in ARMS) + ' |')
    L.append('|---' + '|---' * len(ARMS) + '|')
    for z in Z7:
        row = []
        for k in ARMS:
            s = A[k]['R1b_R1c_zones7'][z]
            o = A[k]['R1d_onset']['zones7'][z]
            row.append('%s / %s / %d / %s' % (f(s['veh_h_0_9000']), f(s['mean_speed_kmh_0_9000']), s['cong_minutes_all_windows'], f(o['onset_s'])))
        L.append('| %s (%s) | %s |' % (z, '–'.join(f(int(x)) for x in A[ARMS[0]]['R1b_R1c_zones7'][z]['bins']) if A[ARMS[0]]['R1b_R1c_zones7'][z]['bins'] else '', ' | '.join(row)))
    # T6 cells
    L.append('\n### T6. R1-c·d plant 31셀(0부터) 혼잡 분 / 막힘 시작 s (셀 규칙: 혼잡 칸 ≥ 1 이 두 창 이어짐)\n')
    L.append('| 셀 | x (m) | fwe 칸 수 | ' + ' | '.join(ARMS) + ' |')
    L.append('|---:|---|---:' + '|---' * len(ARMS) + '|')
    cells = A[ARMS[0]]['R1c_cells']
    for c in sorted(cells, key=int):
        cc = cells[c]
        if cc is None:
            L.append('| %s | (100 m 칸 가운데가 없음) | 0 |%s' % (c, ' – |' * len(ARMS)))
            continue
        row = []
        for k in ARMS:
            x = A[k]['R1c_cells'][c]
            o = A[k]['R1d_onset']['cells'][c]
            row.append('%d / %s' % (x['cong_minutes_all_windows'], f(o['onset_s'])))
        L.append('| %s | %s–%s | %d | %s |' % (c, f(cc['x_m'][0], 0), f(cc['x_m'][1], 0), cc['bins'], ' | '.join(row)))
    # T7 heads
    L.append('\n### T7. R1-e 병목 머리 (10분 이상, 머리 x = 100 m 칸 시작)\n')
    L.append('| 런 | x (m) | 링크 | 셀 | 구역(5) | 분 | 첫 s | 끝 s | 차로 칸 | 가장 느린 차로 | 차로 1/2/3/4 평균 속도 (km/h) |')
    L.append('|---|---:|---|---:|---|---:|---:|---:|---|---:|---|')
    for k in ARMS:
        for h in A[k]['R1e_heads']:
            if h['minutes'] < 10:
                continue
            ln = h.get('lane', {})
            st = ln.get('status')
            if st == 'no_lane_bins':
                lane_s, low, sp = '차로 못 냄', '–', '–'
            else:
                lane_s = '%s %s–%s' % ('전부' if st == 'full' else '부분', f(ln['lane_x_from_m'], 0), f(ln['lane_x_to_m'], 0))
                low = str(ln['lowest_speed_lane'])
                sp = ' / '.join(f(ln['lane_mean_speed_kmh'][str(i)]) for i in range(1, 5))
            L.append('| %s | %s | %s | %s | %s | %d | %s | %s | %s | %s | %s |' % (
                k, f(h['x_m'], 0), h['link'], h['cell'], (h['zone5'] or '–').split('_')[0], h['minutes'], f(h['first_s']), f(h['last_end_s']), lane_s, low, sp))
    L.append('\n- 10분 아래 머리 수(분 합): ' + '; '.join('%s %d개(%d분)' % (k, sum(1 for h in A[k]['R1e_heads'] if h['minutes'] < 10),
                                                               sum(h['minutes'] for h in A[k]['R1e_heads'] if h['minutes'] < 10)) for k in ARMS) + '.')
    # T8 tails
    L.append('\n### T8. R1-f 번짐 (tails.py)\n')
    L.append('| 런 | B1 꼬리 최상류 m (s) | B1 번짐 분 (<4,500 m) | B1 번짐 첫–끝 s | B2 꼬리 최상류 m (s) | M 번짐 분 (B2 꼬리 <6,800 m) | M 번짐 첫–끝 s | S-7 (INV_PHYSICS 와 같음) |')
    L.append('|---|---|---:|---|---|---:|---|---|')
    for k in ARMS:
        t = A[k]['R1f_tails']
        L.append('| %s | %s (%s) | %d | %s | %s (%s) | %d | %s | %s |' % (
            k, f(t['b1_tail_min_m']), f(t['b1_tail_min_at_s']), t['b1_spill_min_lt4500'], rng(t['b1_spill_first_s'], t['b1_spill_last_end_s']),
            f(t['b2_tail_min_m']), f(t['b2_tail_min_at_s']), t['m_spill_min_lt6800'], rng(t['m_spill_first_s'], t['m_spill_last_end_s']),
            '같음' if R['S7'][k]['equal'] else '다름'))
    L.append('\n| 런 | 칸 ' + hdr_blocks() + ' |')
    L.append('|---|---' + '|---:' * 10 + '|')
    for k in ARMS:
        t = A[k]['R1f_tails']
        L.append('| %s | B1 번짐 분 | %s |' % (k, ' | '.join(str(x) for x in blk_sum(t['b1_spill_minutes_300']))))
        L.append('| %s | M 번짐 분 | %s |' % (k, ' | '.join(str(x) for x in blk_sum(t['m_spill_minutes_300']))))
    # T9 ramps / off-ramps / entry / delay
    L.append('\n### T9. R1-g 진입 연결로+접근 링크 재고·대기, 진출 대기 (veh·h, [0, 9000))\n')
    L.append('| 런 | ' + ' | '.join('%s 재고 / 대기' % r for r in RAMPS) + ' | ' + ' | '.join('%s 대기' % o for o in OFFS) + ' |')
    L.append('|---' + '|---:' * 8 + '|')
    for k in ARMS:
        g = A[k]['R1g']
        L.append('| %s | %s | %s |' % (k, ' | '.join('%s / %s' % (f(g['ramps'][r]['stock_veh_h_0_9000']), f(g['ramps'][r]['queued_veh_h_0_9000'])) for r in RAMPS),
                                     ' | '.join(f(g['offramps'][o]['queued_veh_h_0_9000']) for o in OFFS)))
    L.append('\n### T10. R1-g 합류율·삽입율 (veh/h, 900 s 칸 = 300 s 창 셋의 평균)\n')
    L.append('| 런 | 칸 ' + hdr_blocks() + ' |')
    L.append('|---|---' + '|---:' * 10 + '|')
    for k in ARMS:
        g = A[k]['R1g']
        for r in RAMPS:
            L.append('| %s | 합류 %s | %s |' % (k, r, ' | '.join(f(x, 0) for x in blk_rate(g['ramps'][r]['merge_veh_per_h_300']))))
        L.append('| %s | 삽입 74 | %s |' % (k, ' | '.join(f(x, 0) for x in blk_rate(g['ins_74_veh_per_h_300']))))
    L.append('\n### T11. R1-g 진출 대기 (veh·h, 900 s 칸)\n')
    L.append('| 런 | 진출 ' + hdr_blocks() + ' |')
    L.append('|---|---' + '|---:' * 10 + '|')
    for k in ARMS:
        g = A[k]['R1g']
        for o in OFFS:
            L.append('| %s | %s | %s |' % (k, o, ' | '.join(f(x, 2) for x in blk_sum(g['offramps'][o]['queued_veh_h_300']))))
    L.append('\n### T12. R1-g 구역 지체 (veh·h, 108 km/h 기준, fwe_analyze.py:70)\n')
    L.append('| 런 | ' + ' | '.join(Z5N[z] for z in Z5) + ' | 합 |')
    L.append('|---' + '|---:' * 6 + '|')
    for k in ARMS:
        g = A[k]['R1g']
        L.append('| %s | %s | %s |' % (k, ' | '.join(f(g['analyse_zone_delay_vref108'][z]) for z in Z5), f(g['analyse_delay_total_vref108'])))
    # T13 checks
    L.append('\n### T13. 대조\n')
    L.append('| 런 | fwe_analyze 와 같음 (혼잡 분·시작·머리) | 재고·지체 차 최대 | INV_PHYSICS:64-66 (B1·B2·M 시작/분, 머리 분) |')
    L.append('|---|---|---:|---|')
    for k in ARMS:
        c = A[k]['check_vs_analyse']
        same = all(c[z]['cong_minutes_any_equal'] and c[z]['onset_equal'] for z in Z5) and c['heads_top12_equal']
        mx = max(max(abs(c[z]['veh_h_diff']), abs(c[z]['delay_diff'])) for z in Z5)
        x = R['extra_check_inv31'].get(k)
        if x:
            bad = [z for z in ('B1_4200_5300', 'B2_6800_7900', 'M_5300_6800') if not x[z]['equal']] + \
                  ['head %s' % h for h, v in x['heads'].items() if not v['equal']]
            xs = '모두 같음' if not bad else '다름: ' + ', '.join(bad)
        else:
            xs = '(표에 없음)'
        L.append('| %s | %s | %s | %s |' % (k, '같음' if same else '다름', f(mx, 3), xs))
    L.append('\n- 멈춤: %s' % ('없음' if not R['stops'] else json.dumps(R['stops'], ensure_ascii=False)))
    out = FD + '/out/R1_tables.md'
    with open(out, 'w', encoding='utf-8') as g:
        g.write('\n'.join(L) + '\n')
    print('written', out)


if __name__ == '__main__':
    main()
