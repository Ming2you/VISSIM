# -*- coding: utf-8 -*-
"""fwe_r2_md.py - D-K9-106 R2: turn out/R2_pairs.json into Markdown tables (no new numbers, only sums of 300 s cells
into 900 s / 900-end, and veh-weighted speeds from the stored x/y levels).

Usage: python -B fwe_r2_md.py <R2_pairs.json> <out_md>
"""
import hashlib
import json
import sys

S7 = ['74', '10699', '2', '10613', '119', '10702', '24']
ENTRY = ['10639', '10681', '10490', '10484', '70', '68', '129', '31']
EXIT = ['10643', '10682', '10481', '10483']
S19 = S7 + ENTRY + EXIT
LINK_NOTE = {'74': '① U 체인 0 m', '10699': '① 커넥터', '2': '① 본선 4차로', '10613': '① 4→3 차로', '119': '① 본선',
             '10702': '① 커넥터', '24': '① 본선 하류', '10639': '진입 커넥터(RM 10639)', '10681': '진입 커넥터(RM 10681)',
             '10490': '진입 커넥터(RM 10490)', '10484': '진입 커넥터(RM 10484)', '70': '접근(→10639)', '68': '접근(→10681)',
             '129': '접근(→10490)', '31': '접근(→10484)', '10643': '진출 커넥터(신호 배수)', '10682': '진출 커넥터',
             '10481': '진출 커넥터(신호 배수)', '10483': '진출 커넥터'}
PAIR_NAME = {'P-VA': 'V-A − NC3', 'P-B': 'B − NC3', 'P-VSL': 'VSL − NC3', 'P-BVA': 'B − V-A', 'P-J1': 'J1 − NC3 (참고)',
             'Q-joint': 'codex joint − NC', 'Q-window': 'codex window − NC', 'Q-off': 'codex off − NC',
             'Q-fw': 'codex freeway_only − NC', 'Q-urb': 'codex urban_only − NC', 'Q-A1': 'A1 − LNC (참고)',
             'Q-A1j': 'A1 − codex joint (참고, 흔들림 잣대)', 'Q-VSL64': 'vsl_repro vsl − LNC (참고, bin 꼴)'}
V3_ORDER = ['P-VA', 'P-B', 'P-VSL', 'P-BVA', 'P-J1']
Q_ORDER = ['Q-joint', 'Q-window', 'Q-off', 'Q-fw', 'Q-urb', 'Q-A1', 'Q-A1j', 'Q-VSL64']


def f(v, nd=1):
    if v is None:
        return '—'
    s = ('%.' + str(nd) + 'f') % v
    if s.startswith('-'):
        if float(s) == 0:
            return ('%.' + str(nd) + 'f') % 0.0
        return '−' + s[1:]
    if float(s) == 0:
        return s
    return '+' + s


def ws(n300):
    return ['%d–%d' % (w * 900, w * 900 + 900) for w in range(n300 // 3)]


def agg900(arr):
    return [sum(arr[3 * i:3 * i + 3]) for i in range(len(arr) // 3)]


def spd900(xvh, xsp):
    out = []
    for i in range(len(xvh) // 3):
        n = sum(xvh[3 * i:3 * i + 3])
        v = sum((xsp[j] or 0.0) * xvh[j] for j in range(3 * i, 3 * i + 3))
        out.append(v / n if n > 0 else None)
    return out


def spd_range(xvh, xsp, a, b):
    n = sum(xvh[a:b])
    v = sum((xsp[j] or 0.0) * xvh[j] for j in range(a, b))
    return v / n if n > 0 else None


def keys_of(R, pid):
    return [k for k in R['pairs'] if k.split('|')[0] == pid]


def main():
    src, outp = sys.argv[1], sys.argv[2]
    raw = open(src, 'rb').read()
    R = json.loads(raw.decode('utf-8'))
    L = []
    a = L.append
    a('<!-- generated by tools/fwe_r2_md.py from %s (sha256 %s) -->' % (src.replace('\\', '/').split('/')[-1], hashlib.sha256(raw).hexdigest()))
    a('')
    # ---------------- R2-a
    a('### T-a1. R2-a 총합, v3c3 우리 꼴 [0, 9000] s (veh·h, 같은 시드 짝, 시드마다 따로) [실행]')
    a('')
    a('| 짝 | 시드 | d① | d② | Ω701 | ④a | ④b | ④ | Ω 밖 (a) | Ω 밖 (b) |')
    a('|---|---|---:|---:|---:|---:|---:|---:|---:|---:|')
    for pid in V3_ORDER:
        for k in keys_of(R, pid):
            P = R['pairs'][k]
            t = P.get('R2a', {}).get('ours_9000')
            if not t:
                a('| %s | %s | 못 냄 |||||||| ' % (PAIR_NAME[pid], k.split('|')[1]))
                continue
            a('| %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |' % (PAIR_NAME[pid], k.split('|')[1], f(t['S7']), f(t['S19']), f(t['O701']),
                                                                  f(t['A4a']), f(t['U']), f(t['A4']), f(t['outa']), f(t['outb'])))
    a('')
    a('### T-a2. 같은 짝, codex 꼴 [0, 8100] s (v3c3 보조) [실행]')
    a('')
    a('| 짝 | 시드 | d① | d② | Ω701 | ④a | ④b | ④ | Ω 밖 (a) | Ω 밖 (b) |')
    a('|---|---|---:|---:|---:|---:|---:|---:|---:|---:|')
    for pid in V3_ORDER:
        for k in keys_of(R, pid):
            t = R['pairs'][k].get('R2a', {}).get('codex_8100')
            if not t:
                continue
            a('| %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |' % (PAIR_NAME[pid], k.split('|')[1], f(t['S7']), f(t['S19']), f(t['O701']),
                                                                  f(t['A4a']), f(t['U']), f(t['A4']), f(t['outa']), f(t['outb'])))
    a('')
    a('### T-a3. 64cf-s29 짝, codex 꼴 [0, 8100] s (v3c3 와 빼지 않음)')
    a('')
    a('| 짝 | d① | d② | Ω701 | ④a | ④b | ④ | Ω 밖 (a) | Ω 밖 (b) | 원천 |')
    a('|---|---:|---:|---:|---:|---:|---:|---:|---:|---|')
    for pid in Q_ORDER:
        for k in keys_of(R, pid):
            ra = R['pairs'][k].get('R2a', {})
            if not ra:
                a('| %s | 못 냄 ||||||||| ' % PAIR_NAME[pid])
                continue
            form, t = list(ra.items())[0]
            a('| %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |' % (PAIR_NAME[pid], f(t['S7']), f(t['S19']), f(t['O701']), f(t['A4a']),
                                                                  f(t['U']), f(t['A4']), f(t['outa']), f(t['outb']), t.get('source', form)))
    a('')
    # ---------------- R2-f
    a('### T-f. R2-f 시간 모양: 이득 시작·절반 시각 (구역 합 = ① bin 꼴, 누적은 900 s 부터) [실행]')
    a('')
    a('| 짝 | 망·시드 | 누적 d① 900 s–끝 | T_gain_a (s) | T_gain_b (s) | T_half (s) |')
    a('|---|---|---:|---:|---:|---:|')
    for pid in V3_ORDER + Q_ORDER:
        for k in keys_of(R, pid):
            t = R['pairs'][k].get('R2f')
            if not t:
                a('| %s | %s | 못 냄 |||| ' % (PAIR_NAME[pid], k.split('|')[1]))
                continue
            a('| %s | %s | %s | %s | %s | %s |' % (PAIR_NAME[pid], k.split('|')[1], f(t['final_cum_900_end']),
                                                   t['T_gain_a_s'] if t['T_gain_a_s'] is not None else '없음',
                                                   t['T_gain_b_s'] if t['T_gain_b_s'] is not None else '없음',
                                                   t['T_half_s'] if t['T_half_s'] is not None else '없음(끝 ≥ 0)'))
    a('')
    # ---------------- R2-c zone totals
    for zk, title in (('zones5', '다섯 구역(주)'), ('zones7', '일곱 구역(보조)')):
        a('### T-c-%s. R2-c %s: d veh·h, 900 s–끝 합 / d 평균 속도 km/h (900 s–끝, 차량 가중) [실행 fwe_scan]' % (zk[-1], title))
        a('')
        zs = None
        for k in R['pairs']:
            if 'R2c' in R['pairs'][k]:
                zs = list(R['pairs'][k]['R2c'][zk].keys())
                break
        if not zs:
            continue
        a('| 짝 | 망·시드 | ' + ' | '.join('%s veh·h' % z for z in zs) + ' | 합(= d① bin) | ' + ' | '.join('%s km/h' % z for z in zs) + ' |')
        a('|---|---|' + '---:|' * (2 * len(zs) + 1))
        for pid in V3_ORDER + Q_ORDER:
            for k in keys_of(R, pid):
                P = R['pairs'][k]
                if 'R2c' not in P:
                    a('| %s | %s | 못 냄 |' % (PAIR_NAME[pid], k.split('|')[1]))
                    continue
                Z = P['R2c'][zk]
                vh = [sum(Z[z]['d_veh_h'][3:]) for z in zs]
                sp = []
                for z in zs:
                    sx = spd_range(Z[z]['x_veh_h'], Z[z]['x_speed_kmh'], 3, len(Z[z]['x_veh_h']))
                    sy = spd_range(Z[z]['y_veh_h'], Z[z]['y_speed_kmh'], 3, len(Z[z]['y_veh_h']))
                    sp.append(None if sx is None or sy is None else sx - sy)
                a('| %s | %s | %s | %s | %s |' % (PAIR_NAME[pid], k.split('|')[1], ' | '.join(f(v) for v in vh), f(sum(vh)),
                                                  ' | '.join(f(v) for v in sp)))
        a('')
    # ---------------- R2-c zone x 900 s (main zones), per pair
    a('### T-c-t. R2-c 다섯 구역 × 900 s 창: 칸 안 = d veh·h [d 평균 속도 km/h, 차량 가중] [실행]')
    a('')
    for pid in V3_ORDER + Q_ORDER:
        ks = [k for k in keys_of(R, pid) if 'R2c' in R['pairs'][k]]
        if not ks:
            continue
        n300 = R['pairs'][ks[0]]['nw300']
        cols = ws(n300)
        a('**%s**' % PAIR_NAME[pid])
        a('')
        a('| 시드 | 구역 | ' + ' | '.join(cols) + ' |')
        a('|---|---|' + '---:|' * len(cols))
        for k in ks:
            Z = R['pairs'][k]['R2c']['zones5']
            tot = [0.0] * len(cols)
            for z in Z:
                d = agg900(Z[z]['d_veh_h'])
                tot = [x + y for x, y in zip(tot, d)]
                sx = spd900(Z[z]['x_veh_h'], Z[z]['x_speed_kmh'])
                sy = spd900(Z[z]['y_veh_h'], Z[z]['y_speed_kmh'])
                ds = [None if (p is None or q is None) else p - q for p, q in zip(sx, sy)]
                a('| %s | %s | %s |' % (k.split('|')[1], z, ' | '.join('%s [%s]' % (f(v), f(s)) for v, s in zip(d, ds))))
            a('| %s | ① 합 | %s |' % (k.split('|')[1], ' | '.join(f(v) for v in tot)))
        a('')
    # ---------------- R2-b links
    a('### T-b1. R2-b 링크별 d veh·h, 900 s–끝 합 (bin 꼴; ① 7 + 진입 8 + 진출 4) [실행]')
    a('')
    ks_all = [k for pid in V3_ORDER + Q_ORDER for k in keys_of(R, pid) if 'R2b' in R['pairs'][k]]
    heads = ['%s %s' % (R['pairs'][k]['pair'], k.split('|')[1].replace('v3c3-', '').replace('64cf-', '')) for k in ks_all]
    a('| 링크 | 뜻 | ' + ' | '.join(heads) + ' |')
    a('|---|---|' + '---:|' * len(ks_all))
    for l in S19:
        a('| %s | %s | %s |' % (l, LINK_NOTE[l], ' | '.join(f(sum(R['pairs'][k]['R2b']['d_link_300s'][l][3:])) for k in ks_all)))
    for g, L_ in (('① 합', S7), ('진입 쪽 합', ENTRY), ('진출 쪽 합', EXIT), ('② 합', S19)):
        a('| %s | | %s |' % (g, ' | '.join(f(sum(sum(R['pairs'][k]['R2b']['d_link_300s'][l][3:]) for l in L_)) for k in ks_all)))
    a('')
    a('### T-b2. R2-b 링크 × 300 s 칸: 짝마다 가장 작은(−) 6칸과 가장 큰(+) 4칸 (900 s 뒤) [실행]')
    a('')
    a('| 짝 | 망·시드 | 가장 작은 6칸 (링크@창 시작 s: d) | 가장 큰 4칸 |')
    a('|---|---|---|---|')
    for k in ks_all:
        dl = R['pairs'][k]['R2b']['d_link_300s']
        cells = [(dl[l][w], l, w) for l in S19 for w in range(3, len(dl[l]))]
        cells.sort()
        lo = ', '.join('%s@%d: %s' % (l, w * 300, f(v, 2)) for v, l, w in cells[:6])
        hi = ', '.join('%s@%d: %s' % (l, w * 300, f(v, 2)) for v, l, w in cells[::-1][:4])
        a('| %s | %s | %s | %s |' % (PAIR_NAME[R['pairs'][k]['pair']], k.split('|')[1], lo, hi))
    a('')
    # ---------------- R2-e
    a('### T-e. R2-e ① · 진입 쪽 · 진출 쪽 × 900 s 창 d veh·h (bin 꼴) [실행]')
    a('')
    for pid in V3_ORDER + Q_ORDER:
        ks = [k for k in keys_of(R, pid) if 'R2e' in R['pairs'][k]]
        if not ks:
            continue
        cols = ws(R['pairs'][ks[0]]['nw300'])
        a('**%s**' % PAIR_NAME[pid])
        a('')
        a('| 시드 | 묶음 | ' + ' | '.join(cols) + ' | 900–끝 |')
        a('|---|---|' + '---:|' * (len(cols) + 1))
        for k in ks:
            G = R['pairs'][k]['R2e']['group_d_300s']
            for g, nm in (('S7', '①'), ('ENTRY', '진입 쪽'), ('EXIT', '진출 쪽'), ('S19', '②')):
                a('| %s | %s | %s | %s |' % (k.split('|')[1], nm, ' | '.join(f(v) for v in agg900(G[g])), f(sum(G[g][3:]))))
        a('')
    # ---------------- R2-d cells
    a('### T-d1. R2-d 셀별 d veh·h, 900 s–끝 합 (fwe_scan 100 m 칸을 칸 가운데로 셀에 배정; 셀 번호 0부터) [실행]')
    a('')
    ksd = [k for pid in V3_ORDER + Q_ORDER for k in keys_of(R, pid) if 'R2d' in R['pairs'][k]]
    cb = R['definitions']['cell_bounds_m']
    heads = ['%s %s' % (R['pairs'][k]['pair'], k.split('|')[1].replace('v3c3-', '').replace('64cf-', '')) for k in ksd]
    a('| 셀 | 범위 m | ' + ' | '.join(heads) + ' |')
    a('|---|---|' + '---:|' * len(ksd))
    cells = sorted(R['pairs'][ksd[0]]['R2d'].keys()) if ksd else []
    for c in cells:
        i = int(c[1:])
        a('| %d | %.0f–%.0f | %s |' % (i, cb[i], cb[i + 1], ' | '.join(f(sum(R['pairs'][k]['R2d'][c]['d_veh_h'][1:])) for k in ksd)))
    a('')
    a('### T-d2. R2-d 셀 × 900 s 칸 가운데 d veh·h 가 가장 작은 5칸과 그 칸의 d 평균 속도 (900 s 뒤) [실행]')
    a('')
    a('| 짝 | 망·시드 | 가장 작은 5칸 (셀@창 시작 s: d veh·h [d km/h]) |')
    a('|---|---|---|')
    for k in ksd:
        Dd = R['pairs'][k]['R2d']
        cc = []
        for c, v in Dd.items():
            for w in range(1, len(v['d_veh_h'])):
                cc.append((v['d_veh_h'][w], int(c[1:]), w, v['d_speed_kmh'][w]))
        cc.sort()
        a('| %s | %s | %s |' % (PAIR_NAME[R['pairs'][k]['pair']], k.split('|')[1],
                                ', '.join('셀%d@%d: %s [%s]' % (i, w * 900, f(v), f(s)) for v, i, w, s in cc[:5])))
    a('')
    # ---------------- reconcile
    a('### T-r. 조정 줄: 총합(우리 꼴 v3c3 / codex 꼴 64cf) − 300 s 창 합(bin 꼴), 짝 차 veh·h [실행]')
    a('')
    a('| 짝 | 망·시드 | 꼴 | ① | ② | 진입 쪽 | 진출 쪽 |')
    a('|---|---|---|---:|---:|---:|---:|')
    for k in ks_all:
        rc = R['pairs'][k].get('reconcile')
        if not rc:
            continue
        a('| %s | %s | %s | %s | %s | %s | %s |' % (PAIR_NAME[R['pairs'][k]['pair']], k.split('|')[1], rc['S7']['form'],
                                                    *(f(rc[g]['total_minus_windows'], 3) for g in ('S7', 'S19', 'ENTRY', 'EXIT'))))
    a('')
    open(outp, 'w', encoding='utf-8').write('\n'.join(L) + '\n')
    print('md written', outp, len(L))


if __name__ == '__main__':
    main()
