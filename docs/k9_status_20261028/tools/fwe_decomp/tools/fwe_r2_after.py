"""fwe_r2_after.py - D-K9-106 R2, DATA-AFTER cut (PRE_FWE §10 S-12: not a pre-declared cell; report only, never used
for flags or the C1 reference line).

Cut: the "10643 diverge spillback" stretch = cells 5-9 (2,631-4,543 m), the range R1 named for the new 4,300 m head in
NC3 v3c3-s41/s43 (R1_REPORT.md §0 item 4). From out/R2_pairs.json only (no new counts):
  - per pair: d veh*h of cells 5-9 per 900 s window and 900-end; d(1) bin form 900-end; the rest = d(1) - cells 5-9;
    link 10643 (exit connector) d 900-end.
  - same seed, across arms: cells 5-9 900-end for every pair with the same base run (shows whether the piece is
    common to all arms of that seed).
Usage: python -B fwe_r2_after.py <R2_pairs.json> <out_json> <out_md>
"""
import hashlib
import json
import sys

CELLS = ['c05', 'c06', 'c07', 'c08', 'c09']


def f(v, nd=1):
    if v is None:
        return '—'
    s = ('%.' + str(nd) + 'f') % v
    if float(s) == 0:
        return ('%.' + str(nd) + 'f') % 0.0
    return ('−' + s[1:]) if s.startswith('-') else ('+' + s)


def main():
    src, oj, om = sys.argv[1], sys.argv[2], sys.argv[3]
    raw = open(src, 'rb').read()
    R = json.loads(raw.decode('utf-8'))
    cb = R['definitions']['cell_bounds_m']
    out = {'source': src, 'source_sha256': hashlib.sha256(raw).hexdigest(), 'label': '데이터 뒤 (S-12)',
           'cells': CELLS, 'range_m': [cb[5], cb[10]], 'pairs': {}}
    for k, P in R['pairs'].items():
        if 'R2d' not in P:
            continue
        nw = len(P['R2d']['c05']['d_veh_h'])
        per = [sum(P['R2d'][c]['d_veh_h'][w] for c in CELLS) for w in range(nw)]
        piece = sum(per[1:])
        d1 = P['R2f']['final_cum_900_end']
        x10643 = sum(P['R2b']['d_link_300s']['10643'][3:]) if 'R2b' in P else None
        out['pairs'][k] = {'pair': P['pair'], 'x': P['x'], 'y': P['y'], 'cells5_9_per_900s': [round(v, 3) for v in per],
                           'cells5_9_900_end': round(piece, 3), 'd1_900_end': d1, 'd1_rest': round(d1 - piece, 3),
                           'link10643_900_end': None if x10643 is None else round(x10643, 3)}
    json.dump(out, open(oj, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    L = ['<!-- generated by tools/fwe_r2_after.py from R2_pairs.json (sha256 %s); 데이터 뒤 -->' % out['source_sha256'], '']
    L.append('| 짝 | 망·시드 | d① 900–끝 | 셀 5–9 (%.0f–%.0f m) 900–끝 | 나머지 = d① − 셀 5–9 | 링크 10643 900–끝 | 셀 5–9 × 900 s (900 s 부터) |'
             % (cb[5], cb[10]))
    L.append('|---|---|---:|---:|---:|---:|---|')
    for k, v in out['pairs'].items():
        L.append('| %s | %s | %s | %s | %s | %s | %s |' % (v['pair'], k.split('|')[1], f(v['d1_900_end']), f(v['cells5_9_900_end']),
                                                         f(v['d1_rest']), f(v['link10643_900_end']),
                                                         ' / '.join(f(x) for x in v['cells5_9_per_900s'][1:])))
    L.append('')
    L.append('| 기준 런 (같은 시드) | 팔별 셀 5–9 900–끝 |')
    L.append('|---|---|')
    by = {}
    for k, v in out['pairs'].items():
        by.setdefault((v['y'], k.split('|')[1]), []).append('%s %s' % (v['pair'], f(v['cells5_9_900_end'])))
    for (y, s), items in by.items():
        L.append('| %s (%s) | %s |' % (y, s, ' · '.join(items)))
    open(om, 'w', encoding='utf-8').write('\n'.join(L) + '\n')
    print('after written', len(out['pairs']))


if __name__ == '__main__':
    main()
