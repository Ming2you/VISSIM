"""DATA-AFTER view (written after R1 numbers were seen; PRE_FWE S-12). 2026-10-27 KST.
Re-arranges fields already in out/R1_nc.json; computes no new metric.
python -B fwe_r1_after.py -> out/R1_after.md
(a) per 900 s block: minutes of the 4,300 m head, 10643 off-ramp queued veh-h, congested minutes of cells 5-9
    and of cell 0, U-zone congested minutes, B1 spill minutes (tails.py).
"""
import hashlib, json

FD = 'C:/Users/TRLAB/AppData/Local/Temp/claude/C--Users-TRLAB-Desktop----/491ef689-f002-4605-9dc5-e6d363495788/scratchpad/k8/fwe_decomp'
ARMS = ['v3c3-s31', 'v3c3-s41', 'v3c3-s43', '64cf-s29 LNC']
BLK = [(j * 900, j * 900 + 900) for j in range(10)]


def bs(a):
    return [sum(a[3 * j:3 * j + 3]) for j in range(10)]


def main():
    raw = open(FD + '/out/R1_nc.json', 'rb').read()
    R = json.loads(raw.decode('utf-8'))
    L = ['<!-- DATA-AFTER, generated by tools/fwe_r1_after.py from out/R1_nc.json sha256 %s -->' % hashlib.sha256(raw).hexdigest(), '',
         '| 런 | 칸 | ' + ' | '.join('%d–%d' % b for b in BLK) + ' |', '|---|---' + '|---:' * 10 + '|']
    for k in ARMS:
        r = R['arms'][k]['R1']
        h43 = [h for h in r['R1e_heads'] if h['x_m'] == 4300]
        rows = [('머리 4,300 m 분', bs(h43[0]['minutes_300']) if h43 else [0] * 10, 0),
                ('10643 진출 대기 veh·h', bs(r['R1g']['offramps']['10643']['queued_veh_h_300']), 2),
                ('셀 5–9 혼잡 분(셀별 합)', bs([sum(r['R1c_cells'][str(c)]['cong_minutes_300'][i] for c in range(5, 10)) for i in range(30)]), 0),
                ('B1 번짐 분(tails)', bs(r['R1f_tails']['b1_spill_minutes_300']), 0),
                ('셀 0 혼잡 분', bs(r['R1c_cells']['0']['cong_minutes_300']), 0),
                ('U 구역 혼잡 분', bs(r['R1b_R1c_zones5']['U_0_4200']['cong_minutes_300']), 0)]
        for name, v, nd in rows:
            L.append('| %s | %s | %s |' % (k, name, ' | '.join(('{:.%df}' % nd).format(x) for x in v)))
    with open(FD + '/out/R1_after.md', 'w', encoding='utf-8') as g:
        g.write('\n'.join(L) + '\n')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
